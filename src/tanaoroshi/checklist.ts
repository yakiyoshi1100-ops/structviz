export function getIndustries(ids: IndustryId[]): IndustryChecklist[] {
  return INDUSTRY_CHECKLISTS.filter((industry) => ids.includes(industry.id))
}

/** AI検査プロンプトに埋め込むチェックリスト全文を生成する */
export function buildChecklistText(industryIds: IndustryId[]): string {
  const lines: string[] = ['## 共通チェックリスト（業種を問わない業務領域）']

  for (const domain of COMMON_DOMAINS) {
    lines.push(`### ${domain.id}. ${domain.name}`)
    for (const item of domain.items) {
      lines.push(`- ${item}`)
    }
  }

  lines.push('## 横断観点（領域をまたいで抜けやすいもの）')
  for (const check of CROSS_CUTTING) {
    lines.push(`- ${check.label}: ${check.hint}`)
  }

  for (const industry of getIndustries(industryIds)) {
    lines.push(`## 業種別チェックリスト: ${industry.name}（共通への上乗せ分）`)
    for (const item of industry.items) {
      lines.push(`- ${item}`)
    }
  }

  lines.push('## 深掘り14項目（話題に出た業務ごとの充足チェック）')
  lines.push(DEEP_DIVE_ITEMS.map((item, index) => `${index + 1}. ${item}`).join(' '))
  lines.push(
    `特に「${DEEP_DIVE_CRITICAL_ITEMS.join('」「')}」は後工程の構造化とROI試算の成立条件のため、欠けていたらHigh優先とする。`,
  )

  return lines.join('\n')
}
